export function buildMultidisciplinaryTemplates(slugify) {
  return templates.map((template) => ({
    templateKey: template.key,
    name: template.name,
    localizedNames: { en: template.name, it: template.it },
    description: template.description,
    category: template.category,
    academicDomainKey: template.domain,
    disciplineTags: Array.from(
      new Set([template.category, template.domain, ...template.programmes]),
    ),
    recommendedDegreePrograms: template.programmes,
    typicalYear: typicalYearTwo.has(template.key) ? 2 : 1,
    typicalSemester: 1,
    typicalDegreeLevels: template.degrees,
    typicalStage: template.stage,
    curricularStatus: "core",
    version: 1,
    sourceReferences: sources[template.sourceKey],
    validationMetadata: {
      reviewedAt: ACCESSED_AT,
      reviewedBy: "Course Atlas multidisciplinary editorial pass",
      contentStandard: sources[template.sourceKey]
        .map((item) => item.title)
        .join("; "),
      notes: [
        "Canonical synthesis only; never an official university syllabus.",
        "Labels and descriptions are original paraphrases of open frameworks and public course structures.",
        "Estimated workload is intentionally unspecified (0) until a local syllabus supports a defensible value.",
      ],
    },
    topics: template.topics.map(([topicName, subtopicNames], topicIndex) => {
      const topicSlug = slugify(topicName);
      const firstStableId = `${template.key}.subtopic.${topicSlug}-${slugify(subtopicNames[0])}`;
      return {
        stableId: `${template.key}.topic.${topicSlug}`,
        slug: topicSlug,
        name: topicName,
        description: `Core questions, evidence, and methods for ${topicName.toLowerCase()} in ${template.name}.`,
        position: topicIndex + 1,
        subtopics: subtopicNames.map((subtopicName, subtopicIndex) => {
          const depthLevel = depthFor(subtopicIndex);
          const stableId = `${template.key}.subtopic.${topicSlug}-${slugify(subtopicName)}`;
          return {
            stableId,
            slug: `${topicSlug}-${slugify(subtopicName)}`,
            name: subtopicName,
            description: descriptionFor(subtopicName, topicName, depthLevel),
            depthLevel,
            estimatedHours: 0,
            prerequisiteStableIds:
              subtopicIndex > 0 ? [firstStableId] : [],
            optional: false,
            position: subtopicIndex + 1,
          };
        }),
      };
    }),
  }));
}
