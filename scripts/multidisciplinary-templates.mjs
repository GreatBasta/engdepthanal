function depthFor(index) {
  return index === 0 ? "awareness" : index === 1 ? "procedural" : "fluency";
}

function descriptionFor(name, topic, depth) {
  if (depth === "awareness") {
    return `Define and distinguish ${name.toLowerCase()} within ${topic.toLowerCase()}.`;
  }
  if (depth === "procedural") {
    return `Apply standard disciplinary methods to evidence and problems involving ${name.toLowerCase()}.`;
  }
  return `Analyze ${name.toLowerCase()}, justify interpretations, and identify assumptions or limits.`;
}

